def check(project: Project) -> list[dict[str, Any]]:
    """Re-hash files; report drifted/missing sources (URLs are noted, not fetched)."""
    findings: list[dict[str, Any]] = []
    for s in project.spec().sources:
        if s.kind == "file" or s.path:
            path = project.root / (s.path or "")
            if not path.exists():
                findings.append({"source": s.id, "kind": "missing", "detail": s.path})
            elif s.checksum and sha256_of(path) != s.checksum:
                findings.append(
                    {"source": s.id, "kind": "drifted",
                     "detail": f"{s.path} changed since registration"}
                )
        elif s.url:
            findings.append(
                {"source": s.id, "kind": "unchecked-url",
                 "detail": f"{s.url} (verify manually or via the reference cache)"}
            )
    return findings


def citing_sections(project: Project, spec: SpecState, ident: str) -> set[str]:
    """Sections whose workfile slice (or whole file) cites `ident` in a ref marker."""
    citing_files: dict[str, set[int]] = {}
    if project.workfiles_dir.exists():
        for wf in sorted(project.workfiles_dir.glob("*.md")):
            lines = {ln for ln, rid in mdutil.extract_ref_ids(wf.read_text()) if rid == ident}
            if lines:
                citing_files[f"workfiles/{wf.name}"] = lines
    result: set[str] = set()
    for sec in spec.sections:
        if not sec.workfile:
            continue
        path, _, anchor = sec.workfile.partition("#")
        if path not in citing_files:
            continue
        if not anchor:
            result.add(sec.id)
            continue
        text = (project.root / path).read_text()
        sliced = mdutil.extract_section_slice(text, anchor)
        if sliced and any(ident in line for line in sliced.splitlines()):
            result.add(sec.id)
    return result


def drifted_citations(project: Project, spec: SpecState) -> list[dict[str, Any]]:
    """Stale entries for coverage: agreed sections leaning on a drifted source."""
    items: list[dict[str, Any]] = []
    drifted = [f["source"] for f in check(project) if f["kind"] in ("drifted", "missing")]
    for src_id in drifted:
        src = spec.source_by_id(src_id)
        affected = set(src.relates_to if src else []) | citing_sections(project, spec, src_id)
        for sid in sorted(affected):
            sec = spec.section_by_id(sid)
            if sec and sec.maturity in ("agreed", "locked"):
                items.append(
                    {"section": sec.id, "reason": "source-drifted", "source": src_id}
                )
    return items


def orphans(project: Project) -> dict[str, Any]:
    """Uncited sources, and citations pointing at unregistered/missing sources."""
    spec = project.spec()
    known = {s.id for s in spec.sources}
    cited: set[str] = set()
    dangling: list[dict[str, Any]] = []
    if project.workfiles_dir.exists():
        for wf in sorted(project.workfiles_dir.glob("*.md")):
            for lineno, rid in mdutil.extract_ref_ids(wf.read_text()):
                if not rid.startswith("src-"):
                    continue
                cited.add(rid)
                if rid not in known:
                    dangling.append(
                        {"file": f"workfiles/{wf.name}", "line": lineno + 1, "id": rid}
                    )
    return {"uncited": sorted(known - cited), "dangling": dangling}


# ---------------------------------------------------------------------------
# Confidential-verbatim guard (used by lint) + leak patterns (used by bundle)
# ---------------------------------------------------------------------------


def _shingles(text: str, n: int = _SHINGLE_WORDS) -> set[tuple[str, ...]]:
    words = re.findall(r"[\w'-]+", text.lower())
    return {tuple(words[i:i + n]) for i in range(max(0, len(words) - n + 1))}


def confidential_leaks(project: Project) -> list[dict[str, Any]]:
    """Workfile passages that quote a confidential text source verbatim
    (≥ {_SHINGLE_WORDS} consecutive words)."""
    spec = project.spec()
    findings: list[dict[str, Any]] = []
    conf_shingles: dict[str, set[tuple[str, ...]]] = {}
    for s in spec.sources:
        if s.confidential and s.path:
            path = project.root / s.path
            if path.exists() and path.suffix.lower() in _TEXT_SUFFIXES:
                conf_shingles[s.id] = _shingles(path.read_text())
    if not conf_shingles or not project.workfiles_dir.exists():
        return findings
    for wf in sorted(project.workfiles_dir.glob("*.md")):
        wf_shingles = _shingles(wf.read_text())
        for src_id, shingles in conf_shingles.items():
            if wf_shingles & shingles:
                findings.append(
                    {"file": f"workfiles/{wf.name}", "source": src_id,
                     "detail": f"verbatim run (≥{_SHINGLE_WORDS} words) from confidential {src_id}"}
                )
    return findings


def leak_patterns(project: Project) -> list[str]:
    """Strings that must never appear under final/: every src-/ref- id, the
    sources/ and history/references/ paths, and source file basenames."""
    spec = project.spec()
    patterns = ["sources/", "history/references/"]
    patterns += [s.id for s in spec.sources]
    patterns += [Path(s.path).name for s in spec.sources if s.path]
    from . import references as references_mod

    patterns += [r["id"] for r in references_mod.list_references(project)]
    return patterns
