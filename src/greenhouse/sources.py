from .state import today

if TYPE_CHECKING:
    from .models import SpecState
    from .state import Project

_TEXT_SUFFIXES = {".md", ".txt", ".rst", ".csv", ".json", ".yaml", ".yml"}
_SHINGLE_WORDS = 12  # verbatim-run threshold for confidential sources


def sha256_of(path: Path) -> str:
    return "sha256:" + hashlib.sha256(path.read_bytes()).hexdigest()


# ---------------------------------------------------------------------------
# Registration
# ---------------------------------------------------------------------------


def add_source(
    project: Project,
    target: str,
    title: str,
    kind: str | None = None,
    relates_to: list[str] | None = None,
    confidential: bool = False,
    note: str | None = None,
    added_by: str = "user",
    date: dt.date | None = None,
) -> str:
    """Register a file (copied into sources/ if outside it) or a URL.
    Returns the src-NNNN id; sources/INDEX.md is regenerated."""
    spec = project.spec()
    date = date or today()
    relates_to = relates_to or []
    for rel in relates_to:
        if not spec.section_by_id(rel):
            raise GreenhouseError(f"relates_to section {rel!r} does not resolve")

    is_url = bool(re.match(r"https?://", target))
    kind = kind or ("url" if is_url else "file")

    src_id = project.next_source_id()
    entry = CommentedMap()
    entry["id"] = src_id
    entry["title"] = title
    entry["kind"] = kind
    if is_url:
        entry["path"] = None
        entry["url"] = target
        entry["checksum"] = None
    else:
        src_path = Path(target).expanduser()
        if not src_path.exists():
            raise GreenhouseError(f"No such file: {target}")
        project.sources_dir.mkdir(parents=True, exist_ok=True)
        dest = project.sources_dir / src_path.name
        if src_path.resolve() != dest.resolve():
            if dest.exists():
                raise GreenhouseError(f"sources/{dest.name} already exists")
            shutil.copy2(src_path, dest)
        entry["path"] = f"sources/{dest.name}"
        entry["url"] = None
        entry["checksum"] = sha256_of(dest)
    entry["added"] = date
    entry["added_by"] = added_by
    entry["relates_to"] = list(relates_to)
    entry["confidential"] = confidential
    entry["note"] = note
    project._raw_list("sources").append(entry)
    project.save()
    regenerate_index(project)
    return src_id


def regenerate_index(project: Project) -> None:
    spec = project.spec()
    lines = [f"# Sources — {project.name}", "", "<!-- generated by `greenhouse source` -->", ""]
    if not spec.sources:
        lines.append("_No sources registered yet. Add with `greenhouse source add`._")
    else:
        lines += ["| id | kind | title | where | relates to | flags |", "|---|---|---|---|---|---|"]
        for s in spec.sources:
            where = s.path or s.url or "—"
            flags = "confidential" if s.confidential else ""
            lines.append(
                f"| {s.id} | {s.kind} | {s.title} | {where} | "
                f"{', '.join(s.relates_to) or '—'} | {flags} |"
            )
    (project.sources_dir / "INDEX.md").write_text("\n".join(lines) + "\n")


