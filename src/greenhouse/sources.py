"""sources/ — curated input material: indexed in spec-state,
checksummed for drift, citable while working, and barred from final/."""

from __future__ import annotations

import datetime as dt
import hashlib
import re
import shutil
from pathlib import Path
from typing import TYPE_CHECKING, Any

from ruamel.yaml.comments import CommentedMap

from . import mdutil
